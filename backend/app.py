@app.post("/api/auth/register")
def register():
    data = request.get_json(silent=True)
    if not isinstance(data, dict): return jsonify({"error": "A JSON registration object is required."}), 400
    name_value, email_value, password = data.get("name"), data.get("email"), data.get("password")
    if not isinstance(name_value, str) or not isinstance(email_value, str) or not isinstance(password, str): return jsonify({"error": "Name, email, and password must be text values."}), 400
    name, email = name_value.strip(), email_value.strip().lower()
    if not name: return jsonify({"error": "Name is required."}), 400
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email): return jsonify({"error": "A valid email is required."}), 400
    if (error := validate_password(password)): return jsonify({"error": error}), 400
    profile, profile_error = validate_profile(data, require_all=False)
    if profile_error: return jsonify({"error": profile_error}), 400
    style, style_error = preferences.validate_preferences(data.get("style_preferences") or {})
    if style_error: return jsonify({"error": style_error, "errorCode": "invalid_preferences"}), 400
    style = preferences.merge({}, style)
    wait = rate_limited("register_ip", client_ip())
    if wait: return too_many(wait, "Too many sign-up attempts from this connection. Please try again later.")
    record_rate_event("register_ip", client_ip())
    if users.find_one({"email": email}): return jsonify({"error": "Email already exists."}), 409
    if users.find_one({"name": {"$regex": f"^{re.escape(name)}$", "$options": "i"}}): return jsonify({"error": "Username already exists."}), 409
    if profile.get("phone") and users.find_one({"phone": profile["phone"]}): return jsonify({"error": "Phone number already exists."}), 409
    now, user_id = utc_now(), new_id()
    user = {"id": user_id, "name": name, "email": email, "password_hash": bcrypt.generate_password_hash(password).decode("utf-8"), "is_verified": False, "created_at": now, "updated_at": now}
    user.update({k: v for k, v in profile.items() if k in {"phone", "gender", "dob", "age"}})
    try:
        users.insert_one(user)
        if profile or style: user_profiles.insert_one({"user_id": user_id, **profile, **({"style_preferences": style} if style else {}), "created_at": now, "updated_at": now})
        email_sent = create_verification(user_id, email)
    except DuplicateKeyError:
        return jsonify({"error": "An account with one of these details already exists."}), 409
    if email_sent and config.REQUIRE_EMAIL_VERIFICATION:
        message = "We've sent a verification link to your email. Please verify your email before logging in."
    elif email_sent:
        message = "Registration successful. Check your email to verify your account."
    elif config.REQUIRE_EMAIL_VERIFICATION:
        message = "Your account was created, but we couldn't send the verification email just now. Use \"Resend verification email\" on the login page to try again."
    else:
        message = "Registration successful."
    return jsonify({"message": message, "user": public_user(user), "requires_verification": config.REQUIRE_EMAIL_VERIFICATION, "verification_email_sent": email_sent}), 201


@app.post("/api/auth/login")
def login():
    data = request.get_json(silent=True)
    if not isinstance(data, dict): return jsonify({"error": "A JSON login object is required."}), 400
    email_value, password = data.get("email"), data.get("password")
    if not isinstance(email_value, str) or not isinstance(password, str): return jsonify({"error": "Email and password are required."}), 400
    email = email_value.strip().lower()
    legacy_name = str(data.get("name", "")).strip()
    user = users.find_one({"email": email}) if email else users.find_one({"name": {"$regex": f"^{re.escape(legacy_name)}$", "$options": "i"}})
    if not user or not bcrypt.check_password_hash(user.get("password_hash", ""), password or ""):
        return jsonify({"error": "Invalid email or password."}), 401
    if config.REQUIRE_EMAIL_VERIFICATION and not user.get("is_verified"):
        return jsonify({"error": "Please verify your email before logging in.", "errorCode": "email_not_verified", "requires_verification": True}), 403
    token = create_access_token(identity=user["id"])
    response_user = public_user(user)
    response_user["token"] = token
    return jsonify({"message": "Login successful.", "user": response_user}), 200



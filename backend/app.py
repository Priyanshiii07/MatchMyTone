@app.get("/api/quiz/<quiz_type>/<result_id>/pdf")
@require_user
def download_analysis_pdf(quiz_type, result_id):
    collection, normalized = result_collection(quiz_type)
    if collection is None:
        return jsonify({"error": "Invalid analysis type.", "errorCode": "invalid_type"}), 400
    doc = collection.find_one({"id": result_id, "user_id": get_jwt_identity()}, {"_id": 0})
    if not doc:
        return jsonify({"error": "Result not found.", "errorCode": "not_found"}), 404
    started = time.perf_counter()
    try:
        content = pdf_reports.build_pdf(normalized, personalization.attach_styling(normalized, doc, current_user()))
    except Exception as error:
        # Old or unexpected documents must never surface a stack trace; the client offers a retry.
        app.logger.error("PDF generation failed kind=%s error=%s", normalized, type(error).__name__)
        return jsonify({"error": "We couldn't create your summary right now. Please try again.", "errorCode": "pdf_failed"}), 500
    app.logger.info("PDF generated kind=%s bytes=%d duration_ms=%d", normalized, len(content), (time.perf_counter() - started) * 1000)
    response = make_response(content)
    response.headers["Content-Type"] = "application/pdf"
    response.headers["Content-Disposition"] = f'attachment; filename="{pdf_reports.filename_for(normalized)}"'
    response.headers["Cache-Control"] = "no-store"
    return response



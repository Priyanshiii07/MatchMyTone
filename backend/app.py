def update_profile():
    data = request.get_json(silent=True) or {}
    profile, error = validate_profile(data, require_all=True)
    if error: return jsonify({"error": error}), 400
    user = current_user()
    if users.find_one({"phone": profile["phone"], "id": {"$ne": user["id"]}}): return jsonify({"error": "Phone number already exists."}), 409
    now = utc_now()
    cleared = {} if profile.get("gender") else {"$unset": {"gender": ""}}
    users.update_one({"id": user["id"]}, {"$set": {**profile, "updated_at": now}, **cleared})
    user_profiles.update_one({"user_id": user["id"]}, {"$set": {**profile, "updated_at": now}, "$setOnInsert": {"user_id": user["id"], "created_at": now}, **cleared}, upsert=True)
    return jsonify({"message": "Profile updated successfully.", "user": public_user(users.find_one({"id": user["id"]}))})


def decode_camera_frame(image, mime_type):
    """Check the frame is real base64 image data of the declared type; returns an error message or None."""
    if not isinstance(image, str) or len(image) < 100:
        return "A readable camera frame is required."
    if mime_type not in IMAGE_SIGNATURES:
        return "Only JPEG, PNG, or WebP camera frames are supported."
    try:
        raw = base64.b64decode(image, validate=True)
    except (binascii.Error, ValueError):
        return "The camera frame could not be read. Please capture your selfie again."
    if len(raw) > MAX_IMAGE_BYTES:
        return "The camera frame is too large. Please capture your selfie again."
    if not raw.startswith(IMAGE_SIGNATURES[mime_type]) or (mime_type == "image/webp" and raw[8:12] != b"WEBP"):
        return "The camera frame does not match its declared image type."
    return None


def color_document(result, provider, model, user, request_id):
    now = utc_now()
    document = {
        "id": new_id(), "user_id": user["id"], **({"request_id": request_id} if request_id else {}),
        "analysis_provider": provider, "analysis_model": model, "is_face": True,
        "season_type": result["seasonType"], "season_description": result["seasonDescription"],
        "undertone": result["undertone"], "undertone_description": result["undertoneDescription"],
        "skin_age": result["skinAge"], "skin_age_description": result["skinAgeDescription"],
        "colors_to_wear": result["colorsToWear"], "colors_to_avoid": result["colorsToAvoid"], "description": result["description"],
        "created_at": now, "updated_at": now,
    }
    # Styling only changes how the palette is applied; the analysed palette above is stored untouched.
    try:
        document["styling"] = personalization.new_styling("color_analysis", document, user)
    except PyMongoError as error:
        # Preferences unreadable: save the analysis anyway; styling is generated when the result is opened.
        app.logger.warning("Color styling snapshot skipped error=%s", type(error).__name__)
    return document


def color_response(document, cached=False):
    return {
        "id": document["id"], "isFace": True, "analysisProvider": document.get("analysis_provider"), "cached": cached,
        "seasonType": document.get("season_type"), "seasonDescription": document.get("season_description", ""),
        "undertone": document.get("undertone"), "undertoneDescription": document.get("undertone_description", ""),
        "skinAge": document.get("skin_age"), "skinAgeDescription": document.get("skin_age_description", ""),
        "colorsToWear": document.get("colors_to_wear", []), "colorsToAvoid": document.get("colors_to_avoid", []), "description": document.get("description", ""),
        "styling": document.get("styling"),
    }


def pending_color_result(key):
    now = time.monotonic()
    for stale in [item for item, value in PENDING_COLOR_RESULTS.items() if value[0] < now]:
        PENDING_COLOR_RESULTS.pop(stale, None)
    entry = PENDING_COLOR_RESULTS.get(key)
    return entry[1:] if entry else None


@app.post("/api/analyze/color")
@require_user
def analyze_color():
    """Analyze a selfie with the AI provider chain and persist the validated result for the current user."""
    user_id = get_jwt_identity()
    data = request.get_json(silent=True) or {}
    image, mime_type = data.get("image"), str(data.get("mimeType", "image/jpeg"))
    request_id = str(data.get("request_id") or "").strip()[:100]
    if (frame_error := decode_camera_frame(image, mime_type)):
        return jsonify({"error": frame_error, "errorCode": "invalid_image"}), 400
    with ACTIVE_COLOR_LOCK:
        if user_id in ACTIVE_COLOR_ANALYSES:
            return jsonify({"error": "An analysis is already in progress. Please wait for it to finish.", "errorCode": "analysis_in_progress"}), 409
        ACTIVE_COLOR_ANALYSES.add(user_id)
    request_started = time.perf_counter()
    try:
        collection = analysis_collections["color_analysis"]
        if request_id and (existing := collection.find_one({"user_id": user_id, "request_id": request_id}, {"_id": 0})):
            return jsonify(color_response(existing, cached=True)), 200
        pending = pending_color_result((user_id, request_id)) if request_id else None
        if pending:
            result, provider, model = pending
        else:
            profile = user_profiles.find_one({"user_id": user_id}, {"_id": 0}) or current_user()
            previous = collection.find_one({"user_id": user_id, "is_face": True}, {"_id": 0}, sort=[("created_at", -1)])
            provider_started = time.perf_counter()
            try:
                # Only age is shared with the provider: the palette must come from the image, not from gender.
                result, provider, model, _ = color_providers.analyze_color(image, mime_type, previous, {"age": profile.get("age")})
            except ProviderError as error:
                app.logger.warning("Color analysis failed kind=%s duration_ms=%d attempts=%s", error.kind, (time.perf_counter() - request_started) * 1000, [(a["provider"], a["model"], a["outcome"]) for a in error.attempts])
                body = {"error": str(error), "errorCode": f"provider_{error.kind}", "retryable": error.kind in {"temporary", "malformed"}}
                if error.retry_after: body["retryAfterSeconds"] = round(error.retry_after)
                return jsonify(body), 503
            app.logger.info("Color analysis provider=%s model=%s provider_ms=%d", provider, model, (time.perf_counter() - provider_started) * 1000)
            if not result["isFace"]:
                return jsonify({"isFace": False, "description": result["description"], "analysisProvider": provider}), 200
        document = color_document(result, provider, model, current_user(), request_id)
        persistence_started = time.perf_counter()
        try:
            collection.insert_one(document)
        except DuplicateKeyError:
            existing = collection.find_one({"user_id": user_id, "request_id": request_id}, {"_id": 0})
            if existing: return jsonify(color_response(existing, cached=True)), 200
            raise
        except PyMongoError as error:
            if request_id: PENDING_COLOR_RESULTS[(user_id, request_id)] = (time.monotonic() + PENDING_COLOR_TTL_SECONDS, result, provider, model)
            app.logger.error("Color analysis persistence failed error=%s", type(error).__name__)
            return jsonify({"error": "Your colors were analyzed, but the result could not be saved because the database is unavailable. Retry to save it without analyzing again.", "errorCode": "persistence_failed", "retryable": True}), 503
        PENDING_COLOR_RESULTS.pop((user_id, request_id), None)
        app.logger.info("Color analysis saved persistence_ms=%d total_ms=%d", (time.perf_counter() - persistence_started) * 1000, (time.perf_counter() - request_started) * 1000)
        return jsonify(color_response(document)), 201
    finally:
        with ACTIVE_COLOR_LOCK:
            ACTIVE_COLOR_ANALYSES.discard(user_id)


ALLOWED_RESULTS = {
    "skincare": {"Oily Skin", "Dry Skin", "Combination Skin", "Normal Skin", "Sensitive Skin"},
    "body_shape": {"Hourglass", "Rectangle", "Pear", "Apple", "Inverted Triangle"},
    "face_shape": {"Oval", "Round", "Square", "Heart", "Diamond"},
}


def questionnaire_fields(kind, data, user):
    """Validated fields to store for a questionnaire result, or (None, error). Unknown client fields are dropped."""
    answers = data.get("answers")
    if not isinstance(answers, dict) or not answers or not all(isinstance(value, dict) for value in answers.values()):
        return None, "Answers are required."
    if data.get("result") not in ALLOWED_RESULTS[kind]:
        return None, "The result is not a recognised analysis outcome."
    fields = {"answers": answers, "result": data["result"]}
    if kind == "skincare":
        extras, error = preferences.validate_skincare_extras(data.get("routine_extras"))
        if error: return None, error
        # The routine is generated here from the answers; client-supplied recommendations are ignored.
        plan = skincare.skincare_plan(answers, extras)
        return {**fields, "result": plan["skin_type"], "routine_extras": extras, "plan": plan}, None
    overrides, error = personalization.request_overrides(data)
    if error: return None, error
    fields["confidence"] = styling.shape_confidence(answers, fields["result"])
    fields["styling"] = personalization.new_styling(kind, fields, user, overrides)
    return fields, None


def save_analysis(kind):
    persistence_started = time.perf_counter()
    data = request.get_json(silent=True)
    if not isinstance(data, dict): return jsonify({"error": "A JSON result object is required."}), 400
    user = current_user()
    request_id = str(data.get("request_id", "")).strip()[:100]
    if request_id:
        existing = analysis_collections[kind].find_one({"user_id": user["id"], "request_id": request_id}, {"_id": 0})
        if existing:
            return jsonify({"message": f"{kind} result already saved.", "result": public_result(existing)}), 200
    fields, error = questionnaire_fields(kind, data, user)
    if error: return jsonify({"error": error}), 400
    now = utc_now()
    document = {**fields, **({"request_id": request_id} if request_id else {}), "id": new_id(), "user_id": user["id"], "created_at": now, "updated_at": now}
    try:
        analysis_collections[kind].insert_one(document)
    except DuplicateKeyError:
        if request_id:
            existing = analysis_collections[kind].find_one({"user_id": user["id"], "request_id": request_id}, {"_id": 0})
            if existing:
                return jsonify({"message": f"{kind} result already saved.", "result": public_result(existing)}), 200
        raise
    except PyMongoError:
        app.logger.warning("Analysis persistence kind=%s duration_ms=%d outcome=failure", kind, (time.perf_counter() - persistence_started) * 1000)
        raise
    app.logger.info("Analysis persistence kind=%s duration_ms=%d", kind, (time.perf_counter() - persistence_started) * 1000)
    return jsonify({"message": f"{kind} result saved successfully.", "result": public_result(document)}), 201



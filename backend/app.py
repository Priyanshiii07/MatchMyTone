def validate_password(password):
    if not isinstance(password, str) or len(password) < 8:
        return "Password must be at least 8 characters."
    if not re.search(r"[A-Z]", password): return "Password must include an uppercase letter."
    if not re.search(r"[a-z]", password): return "Password must include a lowercase letter."
    if not re.search(r"[0-9]", password): return "Password must include a number."
    if not re.search(r"[^A-Za-z0-9]", password): return "Password must include a special character."
    return None


def validate_profile(data, require_all=False):
    profile = {}
    phone = str(data.get("phone", "")).strip()
    gender = str(data.get("gender", "")).strip().lower()
    dob = str(data.get("dob", "")).strip()
    age = data.get("age")
    if phone:
        if not re.fullmatch(r"\d{10}", phone): return None, "Phone number must be exactly 10 digits."
        profile["phone"] = phone
    elif require_all:
        return None, "Phone number is required."
    # Gender is always optional: it is only a starting point for styling, never a requirement.
    if gender:
        if gender not in {"female", "male", "other"}: return None, "Gender must be female, male or other."
        profile["gender"] = gender
    if dob:
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", dob): return None, "Date of birth must use YYYY-MM-DD."
        profile["dob"] = dob
    elif require_all:
        return None, "Date of birth is required."
    if age not in (None, ""):
        try:
            profile["age"] = int(age)
            if profile["age"] < 0: raise ValueError
        except (TypeError, ValueError): return None, "Age must be a valid number."
    return profile, None


EMAIL_ADDRESS = re.compile(r"[^@\s<>\"']+@[^@\s<>\"']+")


def email_problems():
    """Configuration problems that stop emails being sent (the Resend key is read from the live client so tests can stub it)."""
    problems = [problem for problem in config.email_problems() if not problem.startswith("RESEND_API_KEY")]
    return (["RESEND_API_KEY is not set."] if not resend.api_key else []) + problems


def send_email(message, purpose):
    """Send through Resend. Returns True only when Resend accepted the message.

    Failures are logged with Resend's reason (for example an unverified domain, or the test sender writing to
    someone other than the account owner), with email addresses masked; bodies, links and tokens are never logged.
    """
    if (problems := email_problems()):
        app.logger.warning("Email not sent purpose=%s reason=%s", purpose, " ".join(problems))
        return False
    try:
        resend.Emails.send({"from": config.FROM_EMAIL, **message})
        app.logger.info("Email accepted by Resend purpose=%s", purpose)
        return True
    except Exception as error:
        reason = EMAIL_ADDRESS.sub("<email>", str(getattr(error, "message", "") or error))[:200]
        app.logger.warning("Email delivery failed purpose=%s error=%s reason=%s", purpose, type(error).__name__, reason)
        return False



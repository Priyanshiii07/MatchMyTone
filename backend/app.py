def token_hash(token):
    return hashlib.sha256(token.encode()).hexdigest()


# Abuse limits, counted in MongoDB so they hold across workers: (max events, window).
RATE_LIMITS = {
    "verify_email": [(1, timedelta(seconds=60)), (5, timedelta(days=1))],   # per email address
    "verify_ip": [(10, timedelta(hours=1))],                                # resend requests per client address
    "register_ip": [(10, timedelta(hours=1))],                              # registrations per client address
}


def _aware(value, reference):
    return value.replace(tzinfo=reference.tzinfo) if value.tzinfo is None else value


def rate_key(kind, value):
    return f"{kind}:{hashlib.sha256(str(value).strip().lower().encode()).hexdigest()}"


def rate_limited(kind, value):
    """Seconds until another `kind` event is allowed for `value` (an email or client address), or 0."""
    now, key = utc_now(), rate_key(kind, value)
    longest = max(window for _, window in RATE_LIMITS[kind])
    times = [_aware(doc["created_at"], now) for doc in rate_events.find({"key": key, "created_at": {"$gt": now - longest}}, {"_id": 0, "created_at": 1}).sort("created_at", -1)]
    wait = 0
    for limit, window in RATE_LIMITS[kind]:
        inside = [moment for moment in times if moment > now - window]
        if len(inside) >= limit:
            wait = max(wait, int((inside[limit - 1] + window - now).total_seconds()) + 1)
    return wait


def record_rate_event(kind, value):
    now = utc_now()
    longest = max(window for _, window in RATE_LIMITS[kind])
    rate_events.insert_one({"key": rate_key(kind, value), "created_at": now, "expires_at": now + longest})


def too_many(wait, message):
    response = jsonify({"error": message, "errorCode": "rate_limited", "retryAfter": wait})
    response.headers["Retry-After"] = str(wait)
    return response, 429


def create_verification(user_id, email):
    """Email a new single-use link. Returns True only if Resend accepted the message.

    Only the token's SHA-256 hash is stored. Earlier links are invalidated once the new one is accepted
    for delivery, so a provider failure never leaves the user without a working link they already have.
    """
    token = secrets.token_urlsafe(32)
    now = utc_now()
    digest = token_hash(token)
    email_verifications.insert_one({"token_hash": digest, "user_id": user_id, "email": email, "used": False, "created_at": now, "expires_at": now + timedelta(hours=EMAIL_VERIFICATION_HOURS)})
    record_rate_event("verify_email", email)
    if not send_verification_email(email, token):
        email_verifications.update_one({"token_hash": digest}, {"$set": {"used": True, "undeliverable": True}})
        return False
    email_verifications.update_many({"user_id": user_id, "used": False, "token_hash": {"$ne": digest}}, {"$set": {"used": True, "superseded": True, "used_at": now}})
    return True



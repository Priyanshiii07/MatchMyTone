@app.post("/api/auth/verify-email")
def verify_email():
    """Verify the account the token was issued for. The token alone identifies it; no email or user id is accepted."""
    data = request.get_json(silent=True) or {}
    token = str(data.get("token", "")).strip()
    invalid = (jsonify({"error": "This verification link is invalid or has expired. Request a new one from the login page.", "errorCode": "invalid_token"}), 400)
    if not TOKEN_FORMAT.fullmatch(token): return invalid
    now = utc_now()
    record = email_verifications.find_one({"token_hash": token_hash(token)}, {"_id": 0})
    if not record: return invalid
    user = users.find_one({"id": record["user_id"]}, {"_id": 0, "id": 1, "email": 1, "is_verified": 1})
    # A token is only good for the address it was sent to; if the account's email changed, it no longer applies.
    if not user or user.get("email") != record.get("email"): return invalid
    if record.get("used"):
        if user.get("is_verified"):
            return jsonify({"message": "This link has already been used and your email is verified. You can log in.", "status": "already_verified"}), 200
        if record.get("superseded") or record.get("undeliverable"):
            return jsonify({"error": "A newer verification link has been sent. Please use the most recent email, or request a new link from the login page.", "errorCode": "token_superseded"}), 409
        return jsonify({"error": "This verification link has already been used. Request a new one from the login page.", "errorCode": "token_used"}), 409
    if _aware(record["expires_at"], now) <= now:
        return jsonify({"error": "This verification link has expired. Request a new one from the login page.", "errorCode": "token_expired"}), 410
    claimed = email_verifications.find_one_and_update({"token_hash": token_hash(token), "used": False, "expires_at": {"$gt": now}}, {"$set": {"used": True, "used_at": now}})
    if not claimed: return invalid
    users.update_one({"id": user["id"], "email": record["email"]}, {"$set": {"is_verified": True, "updated_at": now}})
    # Any other outstanding links for this account are now pointless.
    email_verifications.update_many({"user_id": user["id"], "used": False}, {"$set": {"used": True, "used_at": now}})
    return jsonify({"message": "Email verified. You can now log in.", "status": "verified"}), 200


@app.post("/api/auth/resend-verification")
def resend_verification():
    data = request.get_json(silent=True) or {}
    identity = str(data.get("email", "")).strip().lower()
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", identity): return jsonify({"error": "A valid email is required."}), 400
    if email_problems(): return jsonify({"error": "Email delivery is not configured on this server, so verification emails can't be sent yet.", "errorCode": "email_not_configured"}), 503
    generic = {"message": "If that email belongs to an account that still needs verifying, we've sent a new link. Please check your inbox and spam folder."}
    # Limits apply to every address, registered or not, so a 429 says nothing about whether an account exists.
    wait = max(rate_limited("verify_email", identity), rate_limited("verify_ip", client_ip()))
    if wait: return too_many(wait, "A verification email was requested recently. Please wait a little before asking for another.")
    record_rate_event("verify_ip", client_ip())
    user = users.find_one({"email": identity})
    if not user or user.get("is_verified"):
        record_rate_event("verify_email", identity)
        return jsonify(generic)
    if not create_verification(user["id"], user["email"]):
        return jsonify({"error": "We couldn't send the verification email just now. Please try again later.", "errorCode": "email_failed"}), 502
    return jsonify(generic)


@app.post("/api/auth/request-password-reset")
def request_password_reset():
    data = request.get_json(silent=True) or {}
    email = str(data.get("email", "")).strip().lower()
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email): return jsonify({"error": "A valid email is required."}), 400
    # Without an email provider the reset link can never reach the user, so say so instead of pretending.
    if email_problems(): return jsonify({"error": "Password reset email is not configured on this server. Contact the administrator.", "errorCode": "email_not_configured"}), 503
    user = users.find_one({"email": email})
    if user:
        token = uuid.uuid4().hex
        password_resets.insert_one({"token_hash": token_hash(token), "user_id": user["id"], "used": False, "created_at": utc_now(), "expires_at": utc_now() + timedelta(hours=1)})
        if not send_password_reset_email(email, token): return jsonify({"error": "The reset email could not be sent. Please try again later.", "errorCode": "email_failed"}), 502
    return jsonify({"message": "If that email is registered, a password reset link has been sent."})


@app.post("/api/auth/reset-password")
def reset_password():
    data = request.get_json(silent=True) or {}
    token, password = str(data.get("token", "")).strip(), data.get("password")
    if not token: return jsonify({"error": "A password reset token is required."}), 400
    if (error := validate_password(password)): return jsonify({"error": error}), 400
    record = password_resets.find_one_and_update({"token_hash": token_hash(token), "used": False, "expires_at": {"$gt": utc_now()}}, {"$set": {"used": True, "used_at": utc_now()}})
    if not record: return jsonify({"error": "Invalid or expired reset token."}), 400
    users.update_one({"id": record["user_id"]}, {"$set": {"password_hash": bcrypt.generate_password_hash(password).decode("utf-8"), "updated_at": utc_now()}})
    return jsonify({"message": "Password updated. You can log in now."})


